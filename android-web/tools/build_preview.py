"""Package the game as a single-folder web preview (claude.ai artifact or any static host that can't serve .glb/.jpg
next to the page): copies js/lib, embeds models/*.glb and textures/* as base64 in js/embedded_models.js + js/embedded_textures.js, and writes an
index.html without <html>/<head>/<body> wrappers.

    python3 tools/build_preview.py OUT_DIR
"""
import base64, os, re, shutil, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets")
out = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "preview")
if os.path.exists(out):
    shutil.rmtree(out)
os.makedirs(out)
for d in ("js", "lib"):
    shutil.copytree(os.path.join(ROOT, d), os.path.join(out, d))


def b64(p):
    return base64.b64encode(open(p, "rb").read()).decode()


lines = ["// Generated by tools/build_preview.py: binary assets inlined for hosts that only serve pages and scripts."]
lines.append("window.AZ_MODELS = {")
mdir = os.path.join(ROOT, "models")
for f in sorted(os.listdir(mdir)) if os.path.isdir(mdir) else []:
    if f.endswith(".glb"):
        lines.append(f'  "{f[:-4]}": "{b64(os.path.join(mdir, f))}",')
lines.append("};")
open(os.path.join(out, "js", "embedded_models.js"), "w").write("\n".join(lines) + "\n")
lines = ["// Generated by tools/build_preview.py", "window.AZ_TEXTURES = {"]
tdir = os.path.join(ROOT, "textures")
for f in sorted(os.listdir(tdir)) if os.path.isdir(tdir) else []:
    ext = f.rsplit(".", 1)[-1].lower()
    mime = {"jpg": "image/jpeg", "jpeg": "image/jpeg", "png": "image/png", "webp": "image/webp", "hdr": "application/octet-stream"}.get(ext)
    if mime:
        lines.append(f'  "{f}": "data:{mime};base64,{b64(os.path.join(tdir, f))}",')
lines.append("};")
open(os.path.join(out, "js", "embedded_textures.js"), "w").write("\n".join(lines) + "\n")

html = open(os.path.join(ROOT, "index.html")).read()
html = re.sub(r"<!doctype html>\s*<html[^>]*>\s*<head>\s*", "", html, flags=re.I)
html = re.sub(r'<meta charset="utf-8">\s*<meta name="viewport"[^>]*>\s*', "", html)
html = html.replace("</head>", "").replace("<body>", "").replace("</body>", "").replace("</html>", "")
html = html.replace('<script src="lib/three.min.js"></script>', '<script src="js/embedded_models.js"></script>\n<script src="js/embedded_textures.js"></script>\n<script src="lib/three.min.js"></script>', 1)
html += """
<style>
#azhint { position:fixed; left:50%; bottom:calc(10px + env(safe-area-inset-bottom,0px)); transform:translateX(-50%); font:11px "Roboto Mono",monospace; color:#8796ab; letter-spacing:.06em; text-align:center; pointer-events:none; z-index:60; max-width:calc(100% - 32px); }
body.ingame #azhint { display:none; }
@media (pointer:coarse) { #azhint { display:none; } }
</style>
<div id="azhint">DESKTOP: drag left half to move, right half to look · or WASD + arrows · E use · 1/2/3 shift time · F echoes · Space jump · Enter skip line</div>
"""
open(os.path.join(out, "index.html"), "w").write(html)
files = sorted(os.path.relpath(os.path.join(dp, f), out) for dp, _, fs in os.walk(out) for f in fs if f != "index.html")
print("\n".join(files))
